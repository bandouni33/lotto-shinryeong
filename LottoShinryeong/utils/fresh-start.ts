/**
 * "앱을 완전히 종료했다가 다시 켠 것"과 "잠깐 백그라운드로 갔다 돌아온 것"을
 * 구분하기 위한 신호.
 *
 * RN/Expo에는 "앱이 완전히 종료됐다"를 알려주는 JS 콜백이 따로 없다(iOS는 그런
 * 이벤트 자체가 없고, Android도 표준 API로는 못 받는다) — 하지만 모듈 스코프
 * 변수는 이 문제를 별도 네이티브 코드 없이 자연스럽게 해결해준다: 사용자가 최근
 * 앱 목록에서 완전히 스와이프해서 닫으면 iOS/Android 둘 다 프로세스 자체를
 * 종료시키므로, 다음 실행은 이 JS 모듈을 처음부터 다시 로드하는 "콜드 스타트"가
 * 된다 — 반면 홈 버튼으로 잠깐 백그라운드로 보냈다 돌아오는 건 같은 프로세스가
 * 이어지는 것이라 이 모듈도 그대로 메모리에 남아있다. 즉 "이 프로세스에서 처음
 * 호출됐는지" 여부가 곧 "콜드 스타트인지" 여부와 같다.
 */
let consumed = false;

/** 이 프로세스에서 처음 호출될 때만 true를 반환하고, 그 뒤로는 항상 false. */
export function consumeFreshStartFlag(): boolean {
  if (consumed) {
    return false;
  }
  consumed = true;
  return true;
}
